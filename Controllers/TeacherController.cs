/*
    TeacherController is under /api/teacher and is protected with [Authorize(Roles = "Teacher")].
    I read the teacher’s id from the JWT, then I only allow them to change their own assignments.
    Lists use pagination.
    Create/update use DTOs so the client doesn’t send the full entity.
    When grading, I load the submission with its assignment and check that Assignment.TeacherId matches the current user.
 */

